#!/usr/bin/env node
// PreToolUse hook for the Bash and PowerShell tools (see .claude/settings.json).
//
// An additional safety layer, NOT a security boundary: it matches a small,
// fixed list of destructive or rule-breaking command patterns. Claude Code hook
// contract: the event arrives as JSON on stdin; exit code 2 blocks the tool call
// and stderr is shown to Claude; exit code 0 allows it.
//
// Fail closed: if the input cannot be parsed, or a shell call carries no
// readable command, the call is blocked. settings.json additionally turns any
// crash of this script (or a missing `node`) into exit code 2.
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";

const SHELL_TOOLS = new Set(["Bash", "PowerShell"]);

const RULES = [
  [/\bgit\s+push\b[^\n;&|]*\s(?:--force(?:-with-lease)?|-f)\b/, "force push is not allowed"],
  [/\bgit\s+push\b[^\n;&|]*\s(?:\S+:)?(?:refs\/heads\/)?main(?![\w./-])/, "pushing to main is not allowed"],
  [/\bgit\s+(?:commit|push|merge|rebase)\b[^\n;&|]*\s--no-verify\b/, "skipping git hooks (--no-verify) is not allowed"],
  [/\bgit\s+(?:checkout|switch)\s+main\b[^\n]*&&[^\n]*\bgit\s+(?:commit|merge|push)\b/, "changes on main are not allowed"],
  [/\bprisma\s+migrate\s+reset\b/, "prisma migrate reset deletes the database"],
  [/\bprisma\s+db\s+push\b[^\n;&|]*--(?:force-reset|accept-data-loss)\b/, "prisma db push with data loss is not allowed"],
  [/\bdocker\s+volume\s+(?:rm|prune)\b/, "removing Docker volumes deletes data"],
  [/\bdocker\s+(?:compose\b[^\n;&|]*\s)?down\b[^\n;&|]*\s(?:-v|--volumes)\b/, "compose down with volumes deletes data"],
  [/\bdocker\s+system\s+prune\b/, "docker system prune affects other projects"],
  [/\bgit\s+add\b[^\n;&|]*\s(?:\S*\/)?\.env(?!\.example\b|\.staging\.example\b|\.prod\.example\b)[\w.-]*/, "never stage .env files"],
  [/\bgit\s+add\b[^\n;&|]*\bapps\/web\/AGENTS\.md\b/, "apps/web/AGENTS.md is generated by next dev and must not be committed"],
];

/** Staged paths that must never be committed (checked on `git commit`). */
const FORBIDDEN_STAGED = [
  [/^apps\/web\/AGENTS\.md$/, "apps/web/AGENTS.md (generated by next dev)"],
  [/(^|\/)\.env(?!\.example$|\.staging\.example$|\.prod\.example$)[^/]*$/, ".env file"],
  [/\.(?:agekey|pem|key)$|(^|\/)id_(?:rsa|ed25519)$/, "private key file"],
];

function block(reason) {
  process.stderr.write(
    `Blocked by .claude/hooks/guard-shell.mjs: ${reason}. ` +
      "Ask the user to run it themselves if it is really intended.\n",
  );
  process.exit(2);
}

let event;
try {
  event = JSON.parse(readFileSync(0, "utf8"));
} catch {
  block("hook input is not valid JSON, so the command could not be checked");
}
if (!event || typeof event !== "object") {
  block("hook input is not an object, so the command could not be checked");
}
// Only shell tools are checked; settings.json routes nothing else here.
if (typeof event.tool_name === "string" && !SHELL_TOOLS.has(event.tool_name)) {
  process.exit(0);
}
const command = event.tool_input?.command;
if (typeof command !== "string") {
  block("shell call without a readable command");
}

for (const [pattern, reason] of RULES) {
  if (pattern.test(command)) block(reason);
}

if (/\bgit\s+commit\b/.test(command)) {
  let staged = [];
  try {
    staged = execFileSync("git", ["diff", "--cached", "--name-only"], {
      cwd: event.cwd || process.cwd(),
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
      timeout: 5000,
    })
      .split(/\r?\n/)
      .filter(Boolean);
  } catch {
    staged = []; // not a repository: nothing staged to protect
  }
  for (const path of staged) {
    for (const [pattern, what] of FORBIDDEN_STAGED) {
      if (pattern.test(path)) block(`staged ${what} must not be committed: ${path}`);
    }
  }
}

process.exit(0);
